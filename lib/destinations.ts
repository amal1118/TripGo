/** تصفية موحّدة تستخدمها صفحة الهبوط وصفحة الوجهات معاً. */
export function filterDestinations(
  list: Destination[],
  { category = 'all', region = 'الكل', query = '' }:
    { category?: string; region?: string; query?: string } = {},
): Destination[] {
  const q = query.trim().toLowerCase();
  return list.filter((d) => {
    if (category !== 'all' && !d.categories.includes(category as CategoryId)) return false;
    if (region !== 'الكل' && d.region !== region) return false;
    if (!q) return true;
    return [d.name, d.nameEn, d.country, d.spot, d.description, d.region]
      .some((f) => f.toLowerCase().includes(q));
  });
}

/** بطاقات قسم الاستكشاف — أعلى أربع وجهات تقييماً ضمن الفئة المختارة. */
export function trendingFor(category: string, count = 4): Destination[] {
  return filterDestinations(DESTINATIONS, { category })
    .slice()
    .sort((a, b) => b.rating - a.rating)
    .slice(0, count);
}

