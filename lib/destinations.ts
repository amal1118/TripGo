/**
 * lib/destinations.ts — كتالوج الوجهات المقترحة (مصدر واحد للحقيقة).
 *
 * كل ما يظهر في الهيرو، وقسم الاكتشاف، وصفحة الوجهات، وصفحة الوجهة
 * الواحدة يُشتق من مصفوفة DESTINATIONS أدناه — فلا تتناقض بطاقة مع صفحة.
 *
 * الصور من Unsplash عبر CDN مباشر (بلا مفتاح API). كل معرّف تم التحقق من
 * توفّره ومن مطابقته للوجهة بصرياً. المعامل `unsplash()` يوحّد الاقتصاص
 * والجودة لكل الاستدعاءات، فلا تُكتب روابط الصور يدوياً في أي مكان آخر.
 */

export function unsplash(id: string, w: number, h: number, q = 74) {
  return `https://images.unsplash.com/${id}?auto=format&fit=crop&w=${w}&h=${h}&q=${q}`;
}

/* ============================ الأنواع ============================ */

export type CategoryId = 'adventures' | 'relax' | 'culture' | 'family' | 'eco';

export interface DestinationFacts {
  /** أفضل موسم للزيارة. */
  bestTime: string;
  /** مدى الحرارة المعتاد في ذلك الموسم. */
  weather: string;
  language: string;
  /** العملة المحلية كما تُكتب للمسافر. */
  localCurrency: string;
  /** وضع التأشيرة للمسافر الخليجي. */
  visa: string;
  /** زمن الطيران التقريبي من الرياض. */
  flightTime: string;
}

export interface Highlight {
  title: string;
  body: string;
}

export interface Destination {
  /** المُعرّف والمسار معاً: /destinations/{id} */
  id: string;
  name: string;
  nameEn: string;
  country: string;
  /** المنطقة بالعربية — تُستخدم شرائحُ التصفية نصَّها مباشرة. */
  region: string;
  regionEn: string;
  /** المدن أو الأحياء التي تغطيها الوجهة. */
  spot: string;
  /** سطر تشويقي قصير يظهر في صدر صفحة الوجهة. */
  tagline: string;
  /** سطران يصفان روح المكان — يظهران داخل البطاقة. */
  description: string;
  /** فقرتان لصفحة الوجهة. */
  about: string[];
  categories: CategoryId[];
  /** المدة الموصى بها، تظهر أسفل البطاقة. */
  recommendedDays: string;
  /** أقل وأكثر عدد أيام موصى به — يُمرَّر لمخطط الرحلة. */
  days: [number, number];
  rating: number;
  reviews: string;
  /** يبدأ من — للشخص الواحد شاملاً الطيران والإقامة. */
  priceFrom: number;
  currency: string;
  /** صورة الغلاف. */
  image: string;
  /** ثلاث صور إضافية لمعرض صفحة الوجهة. */
  gallery: string[];
  facts: DestinationFacts;
  /** أبرز المعالم — أربعة لكل وجهة. */
  highlights: Highlight[];
  /** تجارب مقترحة تظهر كقائمة. */
  experiences: string[];
  /** نصائح عملية قبل السفر. */
  tips: string[];
  /** شارة «الوجهة الأكثر تفضيلاً» — على واحدة فقط. */
  featured?: boolean;
  /** تظهر في كاروسيل الهيرو. */
  hero?: boolean;
}

