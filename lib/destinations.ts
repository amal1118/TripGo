/** بحث سريع بالمعرّف — تستخدمه صفحة الوجهة وصفحة الوجهات. */
const BY_ID = new Map(DESTINATIONS.map((d) => [d.id, d]));

export function getDestination(id: string): Destination | undefined {
  return BY_ID.get(id);
}

/** وجهات المنطقة نفسها ما عدا الحالية — شريط «وجهات قريبة». */
export function getRelated(id: string, count = 3): Destination[] {
  const current = BY_ID.get(id);
  if (!current) return [];
  const sameRegion = DESTINATIONS.filter((d) => d.id !== id && d.region === current.region);
  const rest = DESTINATIONS.filter((d) => d.id !== id && d.region !== current.region);
  return [...sameRegion, ...rest].slice(0, count);
}

