/**
 * رابط مخطّط الرحلة مملوءاً مسبقاً بهذه الوجهة.
 *
 * النص قصير عمداً: هذا الرابط قد يُعاد ترميزه داخل معامل `next` عند تحويل
 * الزائر لتسجيل الدخول، فيتضاعف طوله. تمرير الوصف كاملاً كان ينتج رابطاً
 * يتجاوز ألف حرف بلا فائدة — الوجهة والمدة تكفيان لبدء الخطة.
 */
export function planUrl(d: Destination) {
  const q = `رحلة إلى ${d.name}، ${d.country} لمدة ${d.days[0]}-${d.days[1]} أيام`;
  return `/plan/new?destination=${encodeURIComponent(d.name)}&q=${encodeURIComponent(q)}`;
}
